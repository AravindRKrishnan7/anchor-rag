-- A maritime professional.
CREATE TABLE IF NOT EXISTS people (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL,
    role       text NOT NULL,
    services   text[] NOT NULL DEFAULT '{}',
    location   text,
    bio        text,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- A company or body people work for (ship manager, port operator, etc.).
CREATE TABLE IF NOT EXISTS organizations (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL UNIQUE,
    org_type   text NOT NULL,
    country    text,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- One job a person held at an organization. end_date NULL = current job.
CREATE TABLE IF NOT EXISTS employment (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id       integer NOT NULL REFERENCES people (id) ON DELETE CASCADE,
    organization_id integer NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    title           text NOT NULL,
    start_date      date NOT NULL,
    end_date        date,
    CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE INDEX IF NOT EXISTS employment_person_id_idx ON employment (person_id);

-- A maritime professional.
CREATE TABLE IF NOT EXISTS people (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL,
    role       text NOT NULL,
    services   text[] NOT NULL DEFAULT '{}',
    location   text,
    bio        text,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- A company or body people work for (ship manager, port operator, etc.).
CREATE TABLE IF NOT EXISTS organizations (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL UNIQUE,
    org_type   text NOT NULL,
    country    text,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- One job a person held at an organization. end_date NULL = current job.
CREATE TABLE IF NOT EXISTS employment (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id       integer NOT NULL REFERENCES people (id) ON DELETE CASCADE,
    organization_id integer NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    title           text NOT NULL,
    start_date      date NOT NULL,
    end_date        date,
    CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE INDEX IF NOT EXISTS employment_person_id_idx ON employment (person_id);

-- A course offered by a training institute (an organization).
CREATE TABLE IF NOT EXISTS courses (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id integer NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    code            text,
    name            text NOT NULL,
    duration_days   integer CHECK (duration_days > 0),
    fee_inr         integer CHECK (fee_inr >= 0),
    description     text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (organization_id, code)
);

CREATE INDEX IF NOT EXISTS courses_organization_id_idx ON courses (organization_id);

-- One scheduled run of a course.
CREATE TABLE IF NOT EXISTS course_batches (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id   integer NOT NULL REFERENCES courses (id) ON DELETE CASCADE,
    start_date  date NOT NULL,
    end_date    date NOT NULL,
    capacity    integer NOT NULL CHECK (capacity > 0),
    location    text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    CHECK (end_date >= start_date)
);

CREATE INDEX IF NOT EXISTS course_batches_course_id_idx ON course_batches (course_id);

-- A report of how many seats are open in a batch. Append-only: the latest
-- report per batch is the current figure, older ones are kept as history.
CREATE TABLE IF NOT EXISTS seat_availability (
    id                    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id              integer NOT NULL REFERENCES course_batches (id) ON DELETE CASCADE,
    seats_available       integer NOT NULL CHECK (seats_available >= 0),
    reported_at           timestamptz NOT NULL DEFAULT now(),
    reported_by_person_id integer NOT NULL REFERENCES people (id)
);

CREATE INDEX IF NOT EXISTS seat_availability_batch_latest_idx
    ON seat_availability (batch_id, reported_at DESC);

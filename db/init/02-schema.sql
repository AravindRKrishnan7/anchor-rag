-- A maritime professional.
CREATE TABLE IF NOT EXISTS people (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL,
    role       text NOT NULL,
    services   text[] NOT NULL DEFAULT '{}',
    location   text,
    bio        text,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- A company or body people work for (ship manager, port operator, etc.).
CREATE TABLE IF NOT EXISTS organizations (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL UNIQUE,
    org_type   text NOT NULL,
    country    text,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- One job a person held at an organization. end_date NULL = current job.
CREATE TABLE IF NOT EXISTS employment (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id       integer NOT NULL REFERENCES people (id) ON DELETE CASCADE,
    organization_id integer NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    title           text NOT NULL,
    start_date      date NOT NULL,
    end_date        date,
    CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE INDEX IF NOT EXISTS employment_person_id_idx ON employment (person_id);

-- A course offered by a training institute (an organization).
CREATE TABLE IF NOT EXISTS courses (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id integer NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    code            text,
    name            text NOT NULL,
    duration_days   integer CHECK (duration_days > 0),
    fee_inr         integer CHECK (fee_inr >= 0),
    description     text,
    created_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (organization_id, code)
);

CREATE INDEX IF NOT EXISTS courses_organization_id_idx ON courses (organization_id);

-- One scheduled run of a course.
CREATE TABLE IF NOT EXISTS course_batches (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id   integer NOT NULL REFERENCES courses (id) ON DELETE CASCADE,
    start_date  date NOT NULL,
    end_date    date NOT NULL,
    capacity    integer NOT NULL CHECK (capacity > 0),
    location    text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    CHECK (end_date >= start_date)
);

CREATE INDEX IF NOT EXISTS course_batches_course_id_idx ON course_batches (course_id);

-- A report of how many seats are open in a batch. Append-only: the latest
-- report per batch is the current figure, older ones are kept as history.
-- source: manual = entered by staff, form = submitted via a web form,
-- sync = pulled from an institute's system (often has no reporting person).
-- pdf = read from a course PDF by the importer when an admin approves it.
-- seats_available <= capacity is enforced by the app when a report is saved.
CREATE TABLE IF NOT EXISTS seat_availability (
    id                    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id              integer NOT NULL REFERENCES course_batches (id) ON DELETE CASCADE,
    seats_available       integer NOT NULL CHECK (seats_available >= 0),
    source                text NOT NULL CHECK (source IN ('manual', 'form', 'sync', 'pdf')),
    reported_at           timestamptz NOT NULL DEFAULT now(),
    reported_by_person_id integer REFERENCES people (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS seat_availability_batch_latest_idx
    ON seat_availability (batch_id, reported_at DESC);

-- Brings an existing database's source check up to date (adds 'pdf').
ALTER TABLE seat_availability DROP CONSTRAINT IF EXISTS seat_availability_source_check;
ALTER TABLE seat_availability ADD CONSTRAINT seat_availability_source_check
    CHECK (source IN ('manual', 'form', 'sync', 'pdf'));

-- Full-text search for the chat tools. Added with ALTER ... IF NOT EXISTS so
-- re-running this file also updates an existing database.

-- array_to_string is only STABLE, which generated columns don't allow. It is
-- safe to treat as immutable for text[].
CREATE OR REPLACE FUNCTION immutable_array_to_string(text[], text) RETURNS text
    LANGUAGE sql IMMUTABLE AS 'SELECT array_to_string($1, $2)';

ALTER TABLE people ADD COLUMN IF NOT EXISTS search tsvector GENERATED ALWAYS AS (
    setweight(to_tsvector('english', name), 'A') ||
    setweight(to_tsvector('english', role), 'A') ||
    setweight(to_tsvector('english', immutable_array_to_string(services, ' ')), 'B')
) STORED;

CREATE INDEX IF NOT EXISTS people_search_idx ON people USING gin (search);

ALTER TABLE courses ADD COLUMN IF NOT EXISTS search tsvector GENERATED ALWAYS AS (
    setweight(to_tsvector('english', name), 'A') ||
    setweight(to_tsvector('english', coalesce(code, '')), 'A')
) STORED;

CREATE INDEX IF NOT EXISTS courses_search_idx ON courses USING gin (search);

-- An interview with a person, loaded from a transcript file by
-- scripts/ingest_transcripts.py. source_file is the re-ingestion key;
-- content_hash lets unchanged files be skipped.
CREATE TABLE IF NOT EXISTS interviews (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id      integer NOT NULL REFERENCES people (id) ON DELETE CASCADE,
    title          text NOT NULL,
    interviewed_on date,
    source_file    text NOT NULL UNIQUE,
    content_hash   text NOT NULL,
    created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS interviews_person_id_idx ON interviews (person_id);

-- One answer from an interview, embedded for semantic search.
-- embedding_model records which model made the vector; vectors from
-- different models can't be compared.
CREATE TABLE IF NOT EXISTS chunks (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    interview_id    integer NOT NULL REFERENCES interviews (id) ON DELETE CASCADE,
    person_id       integer NOT NULL REFERENCES people (id) ON DELETE CASCADE,
    chunk_index     integer NOT NULL,
    content         text NOT NULL,
    embedding       vector(768) NOT NULL,
    embedding_model text NOT NULL,
    search          tsvector GENERATED ALWAYS AS (to_tsvector('english', content)) STORED,
    UNIQUE (interview_id, chunk_index)
);

CREATE INDEX IF NOT EXISTS chunks_person_id_idx ON chunks (person_id);
CREATE INDEX IF NOT EXISTS chunks_embedding_idx ON chunks USING hnsw (embedding vector_cosine_ops);
CREATE INDEX IF NOT EXISTS chunks_search_idx ON chunks USING gin (search);

-- A course change applied from an uploaded PDF, so every edit records its
-- source. changes holds {field: {old, new}} plus the batches added.
CREATE TABLE IF NOT EXISTS course_updates (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id     integer NOT NULL REFERENCES courses (id) ON DELETE CASCADE,
    source_file   text NOT NULL,
    source_sha256 text NOT NULL,
    extracted_at  timestamptz NOT NULL,
    applied_at    timestamptz NOT NULL DEFAULT now(),
    changes       jsonb NOT NULL
);

CREATE INDEX IF NOT EXISTS course_updates_course_id_idx ON course_updates (course_id);

-- An admin who can upload course PDFs and record seat counts. Created with
-- python -m scripts.create_admin. password_hash is scrypt (app/auth.py);
-- plain passwords are never stored.
CREATE TABLE IF NOT EXISTS admins (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          text NOT NULL,
    email         text NOT NULL UNIQUE CHECK (email = lower(email)),
    password_hash text NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now()
);

-- A logged-in admin. Only the SHA-256 of the cookie token is stored, so a
-- leaked row can't be used as a session.
CREATE TABLE IF NOT EXISTS admin_sessions (
    token_sha256 text PRIMARY KEY,
    admin_id     integer NOT NULL REFERENCES admins (id) ON DELETE CASCADE,
    created_at   timestamptz NOT NULL DEFAULT now(),
    expires_at   timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS admin_sessions_admin_id_idx ON admin_sessions (admin_id);

-- Which admin made each change; NULL for changes from before admin login.
-- No ON DELETE, so an admin with history can't be deleted and the trail
-- stays complete.
ALTER TABLE course_updates ADD COLUMN IF NOT EXISTS admin_id integer REFERENCES admins (id);
ALTER TABLE seat_availability
    ADD COLUMN IF NOT EXISTS recorded_by_admin_id integer REFERENCES admins (id);
